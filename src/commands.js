// Slash command definitions: everything lives under /posse.
const { SlashCommandBuilder, PermissionFlagsBits } = require('discord.js');

const posse = new SlashCommandBuilder()
  .setName('posse')
  .setDescription('Princess Posse guild tools')
  .addSubcommand(c => c.setName('help').setDescription('Everything SYSTEM AI can do'))
  .addSubcommand(c => c.setName('roster').setDescription('Who is in the guild (and who is online)')
    .addBooleanOption(o => o.setName('online').setDescription('Only show people online')))
  .addSubcommand(c => c.setName('roles').setDescription('The guild split into tanks, healers and DPS')
    .addBooleanOption(o => o.setName('online').setDescription('Only people online')))
  .addSubcommand(c => c.setName('iam').setDescription('Link your Discord to your main character (sets your Tank/Healer/DPS role here)')
    .addStringOption(o => o.setName('name').setDescription('Your character name').setRequired(true).setAutocomplete(true)))
  .addSubcommand(c => c.setName('profile').setDescription('A crawler\'s gear, item level, talents and professions')
    .addStringOption(o => o.setName('name').setDescription('Character name').setRequired(true).setAutocomplete(true)))
  .addSubcommand(c => c.setName('crafters').setDescription('Who in the guild can make something')
    .addStringOption(o => o.setName('item').setDescription('Item or recipe name, e.g. linen bag').setRequired(true)))
  .addSubcommand(c => c.setName('board').setDescription('Open Help Wanted posts and groups'))
  .addSubcommand(c => c.setName('events').setDescription('Upcoming guild events and signups'))
  .addSubcommand(c => c.setName('post').setDescription('Post to the Help Wanted / Groups board (shows in game after the next sync)')
    .addStringOption(o => o.setName('type').setDescription('Board').setRequired(true)
      .addChoices({ name: 'Help Wanted', value: 'REQUEST' }, { name: 'Group forming', value: 'GROUP' }))
    .addStringOption(o => o.setName('title').setDescription('Short title').setRequired(true).setMaxLength(80))
    .addStringOption(o => o.setName('details').setDescription('Details').setMaxLength(160)))
  .addSubcommand(c => c.setName('event').setDescription('Create a guild event (shows in game after the next sync)')
    .addStringOption(o => o.setName('title').setDescription('Event name').setRequired(true).setMaxLength(80))
    .addStringOption(o => o.setName('when').setDescription('Date and time, e.g. 2026-11-14 20:00 (server time zone)').setRequired(true))
    .addStringOption(o => o.setName('details').setDescription('Details and roles needed').setMaxLength(160)))
  .addSubcommand(c => c.setName('signup').setDescription('Sign up for an event')
    .addStringOption(o => o.setName('event').setDescription('Which event').setRequired(true).setAutocomplete(true))
    .addStringOption(o => o.setName('role').setDescription('Your role (leave empty to use your linked character\'s role)')
      .addChoices({ name: 'Tank', value: 'Tank' }, { name: 'Healer', value: 'Healer' }, { name: 'DPS', value: 'DPS' }, { name: 'Maybe', value: 'Maybe' }, { name: 'Remove my signup', value: 'Remove' })))
  .addSubcommand(c => c.setName('leaderboard').setDescription('Achievement points leaderboard'))
  .addSubcommand(c => c.setName('achievements').setDescription('Recent achievements in the guild')
    .addStringOption(o => o.setName('name').setDescription('Only this character').setAutocomplete(true)))
  .addSubcommand(c => c.setName('officer').setDescription('Officer desk (officers only)')
    .addStringOption(o => o.setName('view').setDescription('What to show').setRequired(true)
      .addChoices({ name: 'Inactive members', value: 'inactive' }, { name: 'Trial members', value: 'trials' }, { name: 'Ban list', value: 'bans' })))
  .addSubcommand(c => c.setName('status').setDescription('When the guild data last synced'))
  .addSubcommand(c => c.setName('setwelcome').setDescription('Greet new Discord members in this channel with System AI lines (admins)'))
  .addSubcommand(c => c.setName('setfeed').setDescription('Post guild news (posts, events, joins, achievements) in this channel (admins)'));

module.exports = { commands: [posse.toJSON()], PermissionFlagsBits };
